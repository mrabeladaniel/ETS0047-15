#4. title()
#he title() method returns a copy of the string where the first letter of each word is capitalized and all other letters are in lowercase.

text = "hello world"
result = text.title()
print(result)

#Output:
#Hello World
#5. capitalize()
#The capitalize() method returns a copy of the string where only the first character is capitalized, and all other characters are converted to lowercase.

#Example:
text = "hello world"
result = text.capitalize()
print(result)

#Output:
#Hello world
#6. swapcase()
#The swapcase() method returns a copy of the string where all uppercase letters are converted to lowercase and all lowercase letters are converted to uppercase.

#Example:
text = "Hello World"
result = text.swapcase()
print(result)

#Output:

#hELLO wORLD
