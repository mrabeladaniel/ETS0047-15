#1. update()
 #Adds or updates key-value pairs from another dictionary.
#Example:
d = {'a': 1, 'b': 2}
d.update({'b': 3, 'c': 4})
print(d) 
 # Output: {'a': 1, 'b': 3, 'c': 4}
#2. values()
#Returns all the values in the dictionary.
#Example:
d = {'x': 10, 'y': 20}
print(d.values()) 
 # Output: dict_values([10, 20])

