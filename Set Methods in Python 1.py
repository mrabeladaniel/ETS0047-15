#1. add()
#Adds one element to the set.
#Example:
s = {1, 2, 3}
s.add(4)
print(s)
# Output: {1, 2, 3, 4}

#2. clear()
#Adds one element to the set.
#Example:
s = {1, 2, 3}
s.clear()
print(s)
# Output: set()

#3. copy()
#Returns a shallow copy of the set.
#Example:
s = {1, 2, 3}
new_s = s.copy()
print(new_s)
# Output: {1, 2, 3}
